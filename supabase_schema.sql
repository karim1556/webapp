BEGIN;

-- ==============================================================================
-- Phantom Limb Telemetry Database Schema (Supabase / PostgreSQL)
-- Target Table: phantom_limb_telemetry
-- ==============================================================================

-- 1. Create Telemetry Table
CREATE TABLE IF NOT EXISTS public.phantom_limb_telemetry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    device_id TEXT DEFAULT 'C6525',
    state INTEGER DEFAULT 1,
    state_label TEXT DEFAULT 'MONITORING',
    finger_detected BOOLEAN DEFAULT true,
    haptic_active BOOLEAN DEFAULT false,
    vibration_intensity INTEGER DEFAULT 0,
    
    -- Modular JSONB payloads (direct match with ESP32 nested firmware structs)
    biometrics JSONB DEFAULT '{}'::jsonb,
    motion_emg JSONB DEFAULT '{}'::jsonb,
    environment JSONB DEFAULT '{}'::jsonb,
    assessment JSONB DEFAULT '{}'::jsonb,
    system JSONB DEFAULT '{}'::jsonb,
    
    -- Flattened scalar columns (auto-populated by trigger for simple SQL queries, charts & ML)
    heart_rate NUMERIC(5, 2),
    spo2 NUMERIC(5, 2),
    hrv_rmssd NUMERIC(6, 2),
    hrv_sdnn NUMERIC(6, 2),
    respiration_rate NUMERIC(5, 2),
    perfusion_index NUMERIC(5, 2),
    pulse_raw_adc INTEGER,
    muscle_spasm_jerk NUMERIC(5, 2),
    posture_score NUMERIC(5, 2),
    emg_tone NUMERIC(6, 2),
    temperature_c NUMERIC(5, 2),
    humidity_sweat NUMERIC(5, 2),
    pain_index NUMERIC(5, 2),
    vas_score NUMERIC(4, 2),
    pain_status TEXT,
    battery_voltage NUMERIC(4, 2),
    battery_percent INTEGER
);

-- 2. Performance Indexes for Rapid Time-Series Dashboard Queries
CREATE INDEX IF NOT EXISTS idx_plt_created_at ON public.phantom_limb_telemetry(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_plt_device_time ON public.phantom_limb_telemetry(device_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_plt_pain ON public.phantom_limb_telemetry(pain_index);
CREATE INDEX IF NOT EXISTS idx_plt_sos_flag
    ON public.phantom_limb_telemetry(device_id, created_at DESC, id DESC)
    WHERE battery_voltage IN (0, 1);

-- 3. Automatic Synchronization Trigger
-- Automatically syncs nested JSON fields <--> flat scalar columns in both directions
CREATE OR REPLACE FUNCTION public.sync_phantom_limb_telemetry()
RETURNS TRIGGER AS $$
BEGIN
    -- Extract from biometrics
    IF NEW.biometrics IS NOT NULL AND NEW.biometrics != '{}'::jsonb THEN
        IF NEW.heart_rate IS NULL AND NEW.biometrics ? 'heart_rate' THEN
            NEW.heart_rate := (NEW.biometrics->>'heart_rate')::numeric;
        END IF;
        IF NEW.spo2 IS NULL AND NEW.biometrics ? 'spo2' THEN
            NEW.spo2 := (NEW.biometrics->>'spo2')::numeric;
        END IF;
        IF NEW.hrv_rmssd IS NULL AND NEW.biometrics ? 'hrv_rmssd' THEN
            NEW.hrv_rmssd := (NEW.biometrics->>'hrv_rmssd')::numeric;
        END IF;
        IF NEW.hrv_sdnn IS NULL AND NEW.biometrics ? 'hrv_sdnn' THEN
            NEW.hrv_sdnn := (NEW.biometrics->>'hrv_sdnn')::numeric;
        END IF;
        IF NEW.respiration_rate IS NULL AND NEW.biometrics ? 'respiration_rate' THEN
            NEW.respiration_rate := (NEW.biometrics->>'respiration_rate')::numeric;
        END IF;
        IF NEW.perfusion_index IS NULL AND NEW.biometrics ? 'perfusion_index' THEN
            NEW.perfusion_index := (NEW.biometrics->>'perfusion_index')::numeric;
        END IF;
        IF NEW.pulse_raw_adc IS NULL AND NEW.biometrics ? 'pulse_raw_adc' THEN
            NEW.pulse_raw_adc := (NEW.biometrics->>'pulse_raw_adc')::integer;
        END IF;
    END IF;

    -- Extract from motion_emg
    IF NEW.motion_emg IS NOT NULL AND NEW.motion_emg != '{}'::jsonb THEN
        IF NEW.muscle_spasm_jerk IS NULL AND NEW.motion_emg ? 'muscle_spasm_jerk' THEN
            NEW.muscle_spasm_jerk := (NEW.motion_emg->>'muscle_spasm_jerk')::numeric;
        END IF;
        IF NEW.posture_score IS NULL AND NEW.motion_emg ? 'posture_score' THEN
            NEW.posture_score := (NEW.motion_emg->>'posture_score')::numeric;
        END IF;
        IF NEW.emg_tone IS NULL AND NEW.motion_emg ? 'emg_tone' THEN
            NEW.emg_tone := (NEW.motion_emg->>'emg_tone')::numeric;
        END IF;
    END IF;

    -- Extract from environment
    IF NEW.environment IS NOT NULL AND NEW.environment != '{}'::jsonb THEN
        IF NEW.temperature_c IS NULL AND NEW.environment ? 'temperature_c' THEN
            NEW.temperature_c := (NEW.environment->>'temperature_c')::numeric;
        END IF;
        IF NEW.humidity_sweat IS NULL AND NEW.environment ? 'humidity_sweat' THEN
            NEW.humidity_sweat := (NEW.environment->>'humidity_sweat')::numeric;
        END IF;
    END IF;

    -- Extract from assessment
    IF NEW.assessment IS NOT NULL AND NEW.assessment != '{}'::jsonb THEN
        IF NEW.pain_index IS NULL AND NEW.assessment ? 'pain_index' THEN
            NEW.pain_index := (NEW.assessment->>'pain_index')::numeric;
        END IF;
        IF NEW.vas_score IS NULL AND NEW.assessment ? 'vas_score' THEN
            NEW.vas_score := (NEW.assessment->>'vas_score')::numeric;
        END IF;
        IF NEW.pain_status IS NULL AND NEW.assessment ? 'pain_status' THEN
            NEW.pain_status := NEW.assessment->>'pain_status';
        END IF;
    END IF;

    -- Extract from system
    IF NEW.system IS NOT NULL AND NEW.system != '{}'::jsonb THEN
        IF NEW.battery_voltage IS NULL AND NEW.system ? 'battery_voltage' THEN
            NEW.battery_voltage := (NEW.system->>'battery_voltage')::numeric;
        END IF;
        IF NEW.battery_percent IS NULL AND NEW.system ? 'battery_percent' THEN
            NEW.battery_percent := (NEW.system->>'battery_percent')::integer;
        END IF;
    END IF;

    -- Sync back to JSONB objects if flat columns were supplied instead
    IF NEW.biometrics IS NULL OR NEW.biometrics = '{}'::jsonb THEN
        NEW.biometrics := jsonb_strip_nulls(jsonb_build_object(
            'heart_rate', NEW.heart_rate,
            'spo2', NEW.spo2,
            'hrv_rmssd', NEW.hrv_rmssd,
            'hrv_sdnn', NEW.hrv_sdnn,
            'respiration_rate', NEW.respiration_rate,
            'perfusion_index', NEW.perfusion_index,
            'pulse_raw_adc', NEW.pulse_raw_adc
        ));
    END IF;

    IF NEW.motion_emg IS NULL OR NEW.motion_emg = '{}'::jsonb THEN
        NEW.motion_emg := jsonb_strip_nulls(jsonb_build_object(
            'muscle_spasm_jerk', NEW.muscle_spasm_jerk,
            'posture_score', NEW.posture_score,
            'emg_tone', NEW.emg_tone
        ));
    END IF;

    IF NEW.environment IS NULL OR NEW.environment = '{}'::jsonb THEN
        NEW.environment := jsonb_strip_nulls(jsonb_build_object(
            'temperature_c', NEW.temperature_c,
            'humidity_sweat', NEW.humidity_sweat
        ));
    END IF;

    IF NEW.assessment IS NULL OR NEW.assessment = '{}'::jsonb THEN
        NEW.assessment := jsonb_strip_nulls(jsonb_build_object(
            'pain_index', NEW.pain_index,
            'vas_score', NEW.vas_score,
            'pain_status', NEW.pain_status
        ));
    END IF;

    IF NEW.system IS NULL OR NEW.system = '{}'::jsonb THEN
        NEW.system := jsonb_strip_nulls(jsonb_build_object(
            'battery_voltage', NEW.battery_voltage,
            'battery_percent', NEW.battery_percent
        ));
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_sync_phantom_limb_telemetry ON public.phantom_limb_telemetry;
CREATE TRIGGER trg_sync_phantom_limb_telemetry
BEFORE INSERT OR UPDATE ON public.phantom_limb_telemetry
FOR EACH ROW
EXECUTE FUNCTION public.sync_phantom_limb_telemetry();

-- 4. Enable Row Level Security (RLS) & Policies
ALTER TABLE public.phantom_limb_telemetry ENABLE ROW LEVEL SECURITY;

-- Allow anonymous ingestion from ESP32 firmware
DROP POLICY IF EXISTS "Allow anonymous telemetry ingestion" ON public.phantom_limb_telemetry;
CREATE POLICY "Allow anonymous telemetry ingestion"
ON public.phantom_limb_telemetry
FOR INSERT
TO anon, authenticated, service_role
WITH CHECK (true);

-- Assign each wearable to the Supabase Auth users who may read its data.
CREATE TABLE IF NOT EXISTS public.phantom_limb_device_access (
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    device_id TEXT NOT NULL,
    PRIMARY KEY (user_id, device_id)
);
ALTER TABLE public.phantom_limb_device_access ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.phantom_limb_device_access FROM anon, authenticated;
GRANT SELECT ON public.phantom_limb_device_access TO authenticated;
DROP POLICY IF EXISTS "Read own device assignments" ON public.phantom_limb_device_access;
CREATE POLICY "Read own device assignments"
ON public.phantom_limb_device_access
FOR SELECT TO authenticated
USING (user_id = (SELECT auth.uid()));

DROP POLICY IF EXISTS "Allow public read access for dashboard" ON public.phantom_limb_telemetry;
DROP POLICY IF EXISTS "Read assigned device telemetry" ON public.phantom_limb_telemetry;
REVOKE SELECT ON public.phantom_limb_telemetry FROM PUBLIC, anon;
GRANT SELECT ON public.phantom_limb_telemetry TO authenticated;
GRANT INSERT ON public.phantom_limb_telemetry TO anon, authenticated;
CREATE POLICY "Read assigned device telemetry"
ON public.phantom_limb_telemetry
FOR SELECT TO authenticated
USING (
    device_id = 'C6525'
    OR (SELECT auth.jwt())->'app_metadata'->'neurosync_doctor' = 'true'::jsonb
    OR EXISTS (
        SELECT 1 FROM public.phantom_limb_device_access AS assignment
        WHERE assignment.user_id = (SELECT auth.uid())
          AND assignment.device_id = phantom_limb_telemetry.device_id
    )
);

-- Register for Realtime if the project uses the publication.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime')
       AND NOT EXISTS (
           SELECT 1 FROM pg_publication_tables
           WHERE pubname = 'supabase_realtime'
             AND schemaname = 'public' AND tablename = 'phantom_limb_telemetry'
       ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.phantom_limb_telemetry;
    END IF;
END;
$$;

COMMIT;
